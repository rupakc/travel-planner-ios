#!/usr/bin/env python3
"""Upstream/tokens.json -> DesignSystem Colors.xcassets + Generated/Palette.swift.

One colorset per `<family>-<stop>` plus `white`: an `any` appearance from `palette`
(light mode) and a `dark` appearance from `dark`, sRGB. `--check` exits 1 when the
committed outputs differ from a fresh generation (including stray colorsets).
"""

import argparse
import json
import shutil
import sys
from pathlib import Path

DS = Path("Packages/VoyagerKit/Sources/DesignSystem")
CATALOG = DS / "Resources" / "Colors.xcassets"
PALETTE = DS / "Generated" / "Palette.swift"
INFO = {"info": {"author": "xcode", "version": 1}}


def hex_to_components(value: str) -> dict:
    h = value.lstrip("#")
    if len(h) != 6:
        raise ValueError(f"expected #rrggbb, got {value!r}")
    r, g, b = (int(h[i : i + 2], 16) / 255 for i in (0, 2, 4))
    return {"red": f"{r:.3f}", "green": f"{g:.3f}", "blue": f"{b:.3f}", "alpha": "1.000"}


def _entry(value: str, dark: bool) -> dict:
    entry = {
        "color": {"color-space": "srgb", "components": hex_to_components(value)},
        "idiom": "universal",
    }
    if dark:
        entry["appearances"] = [{"appearance": "luminosity", "value": "dark"}]
    return entry


def _json(obj) -> str:
    return json.dumps(obj, indent=2, sort_keys=True) + "\n"


def _colorset(light: str, dark: str) -> str:
    return _json({"colors": [_entry(light, False), _entry(dark, True)], "info": INFO["info"]})


def _palette_swift(families, stops) -> str:
    fam = "\n".join(f"    case {f}" for f in families)
    stp = "\n".join(f"    case s{s} = {s}" for s in stops)
    return f"""// Generated by tools/gen_tokens.py from Upstream/tokens.json. Do not edit.
import SwiftUI

public enum Family: String, CaseIterable, Sendable {{
{fam}
}}

public enum Stop: Int, CaseIterable, Sendable {{
{stp}
}}

public enum Palette {{
    /// `<family>-<stop>` colour from the asset catalog (light and dark appearances).
    public static func color(_ family: Family, _ stop: Stop) -> Color {{
        Color("\\(family.rawValue)-\\(stop.rawValue)", bundle: .module)
    }}

    public static let white = Color("white", bundle: .module)
}}
"""


def generate(tokens: dict) -> dict:
    """Return {relative path: file content} for every generated file."""
    light, dark = tokens["palette"], tokens["dark"]
    families = [f for f in light if f != "white"]
    stops = [int(s) for s in light[families[0]]]
    files = {str(CATALOG / "Contents.json"): _json(INFO)}
    for family in families:
        if list(light[family]) != list(dark[family]) or [int(s) for s in light[family]] != stops:
            raise SystemExit(f"gen_tokens: {family} stops differ between palette/dark/other families")
        for stop in light[family]:
            files[str(CATALOG / f"{family}-{stop}.colorset" / "Contents.json")] = _colorset(
                light[family][stop], dark[family][stop]
            )
    files[str(CATALOG / "white.colorset" / "Contents.json")] = _colorset(light["white"], dark["white"])
    files[str(PALETTE)] = _palette_swift(families, stops)
    return files


def _existing(root: Path) -> set:
    found = set()
    catalog = root / CATALOG
    if catalog.is_dir():
        found |= {str(p.relative_to(root)) for p in catalog.rglob("*") if p.is_file()}
    if (root / PALETTE).is_file():
        found.add(str(PALETTE))
    return found


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = ap.parse_args()
    root = args.root
    tokens = json.loads((root / "Upstream" / "tokens.json").read_text())
    files = generate(tokens)
    have = _existing(root)
    if args.check:
        drift = sorted(have - files.keys()) + sorted(
            p for p, c in files.items() if p not in have or (root / p).read_text() != c
        )
        if drift:
            print(f"gen_tokens: {len(drift)} file(s) differ from Upstream/tokens.json:", file=sys.stderr)
            for p in drift[:10]:
                print(f"  {p}", file=sys.stderr)
            print("run: python3 tools/gen_tokens.py", file=sys.stderr)
            return 1
        print(f"gen_tokens: {len(files)} files up to date")
        return 0
    for stale in have - files.keys():
        (root / stale).unlink()
    for d in (root / CATALOG).glob("*.colorset"):
        if not any(d.iterdir()):
            shutil.rmtree(d)
    for path, content in files.items():
        out = root / path
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(content)
    print(f"gen_tokens: wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
